"use client";

import { useMemo, useState } from "react";
import { FileText, Download, Plus, Trash2, Loader2, FolderOpen } from "lucide-react";
import Modal from "@/components/ui/Modal";
import ConfirmModal from "@/components/ui/ConfirmModal";
import Button from "@/components/ui/Button";
import { actionToast } from "@/lib/actions";
import {
  reportCategories,
  reportTemplates,
  type ReportCategory,
  type ReportFormat,
  type SavedReport,
} from "@/lib/reports-analytics-data";

const categoryLabel: Record<ReportCategory, string> = {
  clinical: "Clinical",
  financial: "Financial",
  operational: "Operational",
  compliance: "Compliance",
};

const categoryTone: Record<ReportCategory, string> = {
  clinical: "bg-teal-50 text-brand-teal",
  financial: "bg-status-blue-bg text-status-blue",
  operational: "bg-status-amber-bg text-status-amber",
  compliance: "bg-violet-50 text-violet-600",
};

export default function ReportLibrary({
  reports,
  onGenerate,
  onDelete,
}: {
  reports: SavedReport[];
  onGenerate: (templateId: string, format: ReportFormat) => void;
  onDelete: (id: string) => void;
}) {
  const [filter, setFilter] = useState<"all" | ReportCategory>("all");
  const [generateOpen, setGenerateOpen] = useState(false);
  const [selectedTemplate, setSelectedTemplate] = useState(reportTemplates[0].id);
  const [format, setFormat] = useState<ReportFormat>("PDF");
  const [generating, setGenerating] = useState(false);
  const [downloadingId, setDownloadingId] = useState<string | null>(null);
  const [deleteTarget, setDeleteTarget] = useState<SavedReport | null>(null);

  const filtered = useMemo(
    () => (filter === "all" ? reports : reports.filter((r) => r.category === filter)),
    [reports, filter]
  );

  return (
    <div className="rounded-xl border border-surface-border bg-white shadow-card">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-surface-border p-4">
        <div className="flex items-center gap-3">
          <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-slate-100 text-slate-500">
            <FolderOpen className="h-4 w-4" />
          </span>
          <div>
            <h2 className="text-sm font-bold text-slate-900">Report Library</h2>
            <p className="text-xs text-slate-400">Generated reports, exportable for board packs and regulator submissions</p>
          </div>
        </div>
        <Button variant="primary" onClick={() => setGenerateOpen(true)}>
          <Plus className="h-3.5 w-3.5" />
          Generate New Report
        </Button>
      </div>

      <div className="flex flex-wrap gap-1.5 border-b border-surface-border p-3">
        <button
          onClick={() => setFilter("all")}
          className={`rounded-full border px-2.5 py-1 text-[11px] font-semibold ${
            filter === "all" ? "border-slate-800 bg-slate-800 text-white" : "border-surface-border text-slate-500 hover:bg-slate-50"
          }`}
        >
          All ({reports.length})
        </button>
        {reportCategories.map((c) => (
          <button
            key={c.id}
            onClick={() => setFilter(c.id)}
            className={`rounded-full border px-2.5 py-1 text-[11px] font-semibold ${
              filter === c.id ? "border-slate-800 bg-slate-800 text-white" : "border-surface-border text-slate-500 hover:bg-slate-50"
            }`}
          >
            {c.label} ({reports.filter((r) => r.category === c.id).length})
          </button>
        ))}
      </div>

      <div className="divide-y divide-surface-border">
        {filtered.length === 0 ? (
          <p className="px-4 py-10 text-center text-sm text-slate-400">No reports in this category yet.</p>
        ) : (
          filtered.map((r) => (
            <div key={r.id} className="flex flex-wrap items-center justify-between gap-3 px-4 py-3">
              <div className="flex items-start gap-3">
                <span className={`mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-lg ${categoryTone[r.category]}`}>
                  <FileText className="h-4 w-4" />
                </span>
                <div>
                  <p className="text-sm font-semibold text-slate-800">{r.title}</p>
                  <p className="text-[11px] text-slate-400">
                    {r.range} · Generated by {r.generatedBy} on {r.generatedOn}
                  </p>
                </div>
              </div>
              <div className="flex items-center gap-2">
                <span className="rounded bg-slate-100 px-2 py-1 text-[10px] font-bold uppercase text-slate-500">
                  {r.format} · {r.sizeKb >= 1024 ? `${(r.sizeKb / 1024).toFixed(1)} MB` : `${r.sizeKb} KB`}
                </span>
                <button
                  onClick={() => {
                    setDownloadingId(r.id);
                    setTimeout(() => {
                      setDownloadingId(null);
                      actionToast("Report downloaded", `${r.title}.${r.format.toLowerCase()} saved to your downloads.`, "success");
                    }, 600);
                  }}
                  disabled={downloadingId === r.id}
                  className="flex items-center gap-1 rounded-md border border-surface-border bg-white px-2.5 py-1.5 text-[11px] font-semibold text-slate-600 hover:bg-slate-50 disabled:opacity-60"
                >
                  {downloadingId === r.id ? <Loader2 className="h-3 w-3 animate-spin" /> : <Download className="h-3 w-3" />}
                  Download
                </button>
                <button
                  onClick={() => setDeleteTarget(r)}
                  className="flex items-center gap-1 rounded-md border border-surface-border bg-white px-2.5 py-1.5 text-[11px] font-semibold text-status-red hover:bg-red-50"
                >
                  <Trash2 className="h-3 w-3" />
                </button>
              </div>
            </div>
          ))
        )}
      </div>

      <Modal
        open={generateOpen}
        onClose={() => setGenerateOpen(false)}
        title="Generate New Report"
        description="Choose a template and export format"
        size="md"
        footer={
          <>
            <Button variant="secondary" onClick={() => setGenerateOpen(false)}>Cancel</Button>
            <Button
              variant="primary"
              loading={generating}
              onClick={() => {
                setGenerating(true);
                setTimeout(() => {
                  setGenerating(false);
                  setGenerateOpen(false);
                  onGenerate(selectedTemplate, format);
                  const tpl = reportTemplates.find((t) => t.id === selectedTemplate);
                  actionToast("Report generated", `${tpl?.title ?? "Report"} is ready in the library.`, "success");
                }, 900);
              }}
            >
              Generate Report
            </Button>
          </>
        }
      >
        <div className="space-y-3">
          <div>
            <label className="text-[11px] font-semibold uppercase tracking-wide text-slate-400">Template</label>
            <div className="mt-1.5 max-h-56 space-y-1.5 overflow-y-auto pr-1">
              {reportTemplates.map((tpl) => (
                <button
                  key={tpl.id}
                  onClick={() => setSelectedTemplate(tpl.id)}
                  className={`w-full rounded-md border p-2.5 text-left text-xs ${
                    selectedTemplate === tpl.id
                      ? "border-brand-teal bg-teal-50/60"
                      : "border-surface-border hover:bg-slate-50"
                  }`}
                >
                  <p className="font-semibold text-slate-800">{tpl.title}</p>
                  <p className="mt-0.5 text-[11px] text-slate-400">{tpl.description}</p>
                  <span className={`mt-1 inline-block rounded px-1.5 py-0.5 text-[10px] font-bold ${categoryTone[tpl.category]}`}>
                    {categoryLabel[tpl.category]}
                  </span>
                </button>
              ))}
            </div>
          </div>

          <div>
            <label className="text-[11px] font-semibold uppercase tracking-wide text-slate-400">Export Format</label>
            <div className="mt-1.5 flex gap-2">
              {(["PDF", "CSV", "XLSX"] as ReportFormat[]).map((f) => (
                <button
                  key={f}
                  onClick={() => setFormat(f)}
                  className={`flex-1 rounded-md border px-3 py-2 text-xs font-semibold ${
                    format === f ? "border-slate-800 bg-slate-800 text-white" : "border-surface-border text-slate-500 hover:bg-slate-50"
                  }`}
                >
                  {f}
                </button>
              ))}
            </div>
          </div>
        </div>
      </Modal>

      <ConfirmModal
        open={!!deleteTarget}
        onClose={() => setDeleteTarget(null)}
        onConfirm={() => {
          if (deleteTarget) {
            onDelete(deleteTarget.id);
            actionToast("Report deleted", `${deleteTarget.title} removed from the library.`, "info");
          }
          setDeleteTarget(null);
        }}
        variant="delete"
        title="Delete this report?"
        description={deleteTarget ? `"${deleteTarget.title}" will be permanently removed from the report library.` : ""}
        confirmLabel="Delete Report"
      />
    </div>
  );
}
